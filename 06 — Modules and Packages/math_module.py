
# Python Math Module

import math

# Square root
print("Square root of 64:", math.sqrt(64))

# Greatest common divisor
print("GCD of 12 and 18:", math.gcd(12, 18))

# Factorial
print("Factorial of 5:", math.factorial(5))

# Power
print("2 raised to 4:", math.pow(2, 4))

# Ceiling and floor
print("Ceiling of 4.2:", math.ceil(4.2))
print("Floor of 4.8:", math.floor(4.8))

# Constants
print("Value of pi:", round(math.pi, 2))
print("Value of e:", round(math.e, 2))

# Absolute value
print("Absolute value:", math.fabs(-15.5))
