"""
Python Basics - Print and Comments
----------------------------------
Demonstrates Python print statements and comments.
"""

# Single-line comment
print("Hello, Python!")

# Printing multiple values
name = "Madan"
age = 22

print("Name:", name)
print("Age:", age)

# Using f-string
print(f"My name is {name} and I am {age} years old.")

# Printing multiple lines
print("Python")
print("is")
print("easy to learn.")

# Escape characters
print("Hello\nWorld")
print("Python\tProgramming")

# Using sep
print("2026", "09", "29", sep="-")

# Using end
print("Hello", end=" ")
print("World")

"""
This is a
multi-line comment.
"""

# Comments are useful for explaining code.
# They are ignored by the Python interpreter.